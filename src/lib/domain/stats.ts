/**
 * Медиана. `null` на пустом массиве — НЕ 0: «нет данных» и «ровно ноль» это
 * разные ответы, а метрика времени реакции с нулём вместо прочерка врёт в
 * приятную сторону.
 *
 * Входной массив не мутируется (сортируется копия) — иначе вызывающий получил бы
 * переставленные данные как побочный эффект чтения.
 */
export function median(values: number[]): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = sorted.length >> 1;
  return sorted.length % 2 === 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

/**
 * Доля `part` от `total` в диапазоне 0..1. При `total === 0` — 0, а не `NaN`:
 * `NaN%` в интерфейсе выглядит как сломанная страница, а пустая воронка —
 * штатное состояние нового аккаунта.
 */
export function share(part: number, total: number): number {
  if (total === 0) return 0;
  return part / total;
}
