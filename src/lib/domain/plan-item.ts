/**
 * S-FIX-BATCH-1: предикат «строка плана».
 *
 * Строка плана — задача, пришедшая импортом плана внедрения (`PlanImport`) и
 * живущая на доске «План» и в Ганте проекта. В общем списке задач ей места нет:
 * она не личная работа и не самостоятельная проектная задача, а строка WBS,
 * у которой уже есть свой экран. Показ её в списке даёт две болезни сразу —
 * список раздут строками вида «1.3 Согласование протокола», а осмысленные задачи
 * в нём тонут.
 *
 * ── Почему признак именно такой ──
 * Разведка по проду (09.08.2026): 103 задачи с `wbs_code`, и у ВСЕХ проставлен
 * `project_id` — строк с кодом, но без проекта, нет ни одной. Поэтому отдельной
 * колонки `is_plan_item` не заводили: `wbs_code` уже является признаком.
 *
 * Второй конъюнкт (`project_id`) — не украшение, а страховка от невидимки.
 * Скрывать имеет право только тот, у кого есть другой экран: строка плана живёт
 * на доске проекта. Задача с `wbs_code`, но без проекта, на доску не попадёт
 * никуда — спрятав её из списка, мы стёрли бы её из интерфейса совсем. Сегодня
 * таких нет; предикат написан так, чтобы завтрашняя не пропала молча.
 *
 * ⚠️ Это НЕ признак мусора из «Личного». Те 398 строк (пять прогонов импорта,
 * project_id = NULL) `wbs_code` не имеют вовсе — их лечит чистка данных
 * (`supabase/migrations/116_cleanup_orphan_import_tasks.sql`), а не фильтр.
 */

/** Минимальная форма задачи: только поля, от которых зависит признак. */
export interface PlanItemLike {
  project_id?: string | null;
  wbs_code?: string | null;
}

export function isPlanItem(task: PlanItemLike): boolean {
  // Пустая строка — не код: PlanImport пишет `row.wbs || null`, но ручной ввод в
  // TaskModal и старые строки могут дать '' или пробелы.
  const hasWbs = !!task.wbs_code?.trim();
  return hasWbs && !!task.project_id;
}

/** Обратный отбор: то, что показывает список задач. */
export function excludePlanItems<T extends PlanItemLike>(tasks: T[]): T[] {
  return tasks.filter((t) => !isPlanItem(t));
}
