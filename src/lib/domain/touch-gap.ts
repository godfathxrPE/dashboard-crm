import { diffDaysKey, mskDateKey } from '@/lib/utils/date-helpers';

// ═══════════════════════════════════════════════════════
// S-DEAL-NEXTSTEP-1 (W2): «N дн. без касания» — строка ожидания под шагом.
//
// ⚠️ ЭТО НЕ «БЕЗ ОТВЕТА». Спека W2 просит «ждём {имя} · N дн. без ответа», и
// посчитать это нечем: направления у касания в схеме нет (`calls` колонки
// `direction` не имеет, `activities.type` различает вид, а не сторону), поля
// «кого ждём» у сделки нет, а входящих событий система не знает вовсе — лента
// собирается из НАШИХ действий, у каждого события актор из своей организации.
// Напечатать «без ответа» по числу дней с нашего последнего действия значило бы
// соврать ровно так же, как «действует ещё 5 дн.» на отклонённом КП
// (S-DEAL-QUOTE-REASON-1). Печатаем то, что правда: сколько дней НИКТО НЕ
// КАСАЛСЯ сделки с нашей стороны.
//
// ⚠️ ЛЕНТА СОДЕРЖИТ БУДУЩЕЕ. `taskToEvent` ставит дату события в
// `deadline ?? created_at` (`lib/timeline/adapters.ts`), поэтому задача со сроком
// на четверг стоит в ленте ПЕРВОЙ. Замер на проде 08.09: из 24 сделок у 2 верхнее
// событие датировано будущим. Без отсечки строка показала бы «0 дн. без касания»
// на сделке, к которой неделю никто не прикасался, — то самое враньё, ради отказа
// от которого «без ответа» и заменено на «без касания».
//
// Правило якоря — то же, что у `DealLastEvent` (`:107–118`), и перенесено сюда
// НЕ вместо него: виджет остаётся собственным потребителем правила, у него своя
// цель (заголовок события и его следствия). Общая здесь — только отсечка.
//
// Правила модуля: ноль запросов, ноль `Date.now()` внутри — «сейчас» приходит
// аргументом (правило проекта, журнал `leadStaleness`): без этого граница суток
// непроверяема, а именно она здесь и есть предмет.
// ═══════════════════════════════════════════════════════

/**
 * Порог показа. Меньше трёх дней — это не сигнал, а нормальный ход работы:
 * строка «1 дн. без касания» на сделке, которой занимались вчера, обесценила бы
 * саму строку.
 */
export const TOUCH_GAP_MIN_DAYS = 3;

/** Событие ленты в объёме, который нужен расчёту (не весь `TimelineEvent`). */
export interface TouchGapEvent {
  /** ISO-таймстамп события. */
  date: string;
  kind: string;
  /** Сырой `activity_log.event_type` — есть только у `kind === 'activity'`. */
  eventType?: string | null;
}

/**
 * Годится ли событие в якорь «последнего касания».
 *
 * `project_updated` — след правки полей, а не касание: строка «Дата шага: 1 → 2
 * сент» появляется от самого редактирования шага, и засчитывать её за касание
 * значит обнулять счётчик при каждом взгляде на карточку.
 */
function isTouch(e: TouchGapEvent, nowMs: number): boolean {
  const at = Date.parse(e.date);
  if (Number.isNaN(at) || at > nowMs) return false;
  return !(e.kind === 'activity' && e.eventType === 'project_updated');
}

/**
 * Календарных дней МСК от последнего касания до `now`.
 *
 * `null` — касаний нет вовсе. Лента, где все события в будущем или только
 * `project_updated`, — это тоже «нет касаний»: пусто ≠ ноль дней, и печатать
 * «0 дн.» там нельзя.
 *
 * ⚠️ Берётся МАКСИМУМ по дате, а не первое подходящее. Хук отдаёт ленту
 * отсортированной, но функция про порядок входа не знает и знать не должна:
 * `find` по несортированной фикстуре молча вернул бы не тот якорь.
 *
 * ⚠️ Счёт по календарным ключам МСК (`mskDateKey` + `diffDaysKey`), а не
 * `(now - at) / 86400000`: «дней без касания» — это разница КАЛЕНДАРНЫХ дней
 * пользователя, и дробные сутки уехали бы на день на любой границе.
 */
export function touchGapDays(events: readonly TouchGapEvent[], now: Date): number | null {
  const nowMs = now.getTime();

  let lastAt = -Infinity;
  for (const e of events) {
    if (!isTouch(e, nowMs)) continue;
    const at = Date.parse(e.date);
    if (at > lastAt) lastAt = at;
  }
  if (lastAt === -Infinity) return null;

  return diffDaysKey(mskDateKey(new Date(lastAt)), mskDateKey(now));
}
