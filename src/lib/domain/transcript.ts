/**
 * Текст, который вообще имеет смысл сохранять. Пустой и пробельный — не имеет:
 * пустой транскрипт не отличим от отсутствующего, но при этом даёт строку в БД,
 * ложный бейдж «Расшифровка» в списке и лишнюю версию в истории.
 */
export function isSavableTranscriptText(text: string | null | undefined): boolean {
  return typeof text === 'string' && text.trim().length > 0;
}

/**
 * Нужна ли НОВАЯ строка транскрипта или сгодится последняя существующая.
 *
 * ⚠️ Правило «изменился текст → новый транскрипт, история сохраняется» — не
 * оптимизация, а требование: человек правит машинную расшифровку руками, и правка
 * не должна затирать машинную версию (по ней уже могли пройти прогоны).
 * Обратная сторона того же правила — дублей быть не должно: тот же текст той же
 * сущности переиспользует ту же строку.
 *
 * Сравнение точное, без trim: «текст с висящим пробелом» — это уже другая версия
 * ровно в том же смысле, в каком ею является любая другая правка. Нормализация
 * здесь молча склеила бы версии, которые edge-функция видит как разные.
 */
export function shouldCreateNewTranscript(
  lastContent: string | null | undefined,
  nextText: string,
): boolean {
  return lastContent !== nextText;
}

/**
 * Объём расшифровки для бейджа в списке звонков/встреч: «12 тыс. знаков».
 *
 * Тысячи, а не точное число: человеку в списке важен порядок («это часовой
 * разговор, а это реплика»), а не 12 431 против 12 430.
 */
export function formatCharCount(chars: number): string {
  if (!Number.isFinite(chars) || chars <= 0) return '0 знаков';
  if (chars < 1000) return `${Math.round(chars)} знаков`;
  return `${Math.round(chars / 1000).toLocaleString('ru')} тыс. знаков`;
}
