// Транскрипт как самостоятельная сущность — чистые решения без Supabase.
//
// S-AI-VIS-1: раньше эти правила жили внутри мутации `useStartRun` и работали
// только в момент запуска пресета. Не нажал пресет — расшифровка умирала вместе
// с состоянием компонента (на живой БД: 4 транскрипта на все прогоны расшифровки,
// из них `source='audio'` — один). Правила вынесены сюда, чтобы ими пользовались
// оба вызывающих: запуск пресета и сохранение по факту готовности.
// ═══════════════════════════════════════════════════════

/**
 * Текст, который вообще имеет смысл сохранять. Пустой и пробельный — не имеет:
 * пустой транскрипт не отличим от отсутствующего, но при этом даёт строку в БД,
 * ложный бейдж «Расшифровка» в списке и лишнюю версию в истории.
 */
export function isSavableTranscriptText(text: string | null | undefined): boolean {
  return typeof text === 'string' && text.trim().length > 0;
}

/**
 * Нужна ли НОВАЯ строка транскрипта или сгодится последняя существующая.
 *
 * ⚠️ Правило «изменился текст → новый транскрипт, история сохраняется» — не
 * оптимизация, а требование: человек правит машинную расшифровку руками, и правка
 * не должна затирать машинную версию (по ней уже могли пройти прогоны).
 * Обратная сторона того же правила — дублей быть не должно: тот же текст той же
 * сущности переиспользует ту же строку.
 *
 * Сравнение точное, без trim: «текст с висящим пробелом» — это уже другая версия
 * ровно в том же смысле, в каком ею является любая другая правка. Нормализация
 * здесь молча склеила бы версии, которые edge-функция видит как разные.
 */
export function shouldCreateNewTranscript(
  lastContent: string | null | undefined,
  nextText: string,
): boolean {
  return lastContent !== nextText;
}

/**
 * Объём расшифровки для бейджа в списке звонков/встреч: «12 тыс. знаков».
 *
 * Тысячи, а не точное число: человеку в списке важен порядок («это часовой
 * разговор, а это реплика»), а не 12 431 против 12 430.
 */
export function formatCharCount(chars: number): string {
  if (!Number.isFinite(chars) || chars <= 0) return '0 знаков';
  if (chars < 1000) return `${Math.round(chars)} знаков`;
  return `${Math.round(chars / 1000).toLocaleString('ru')} тыс. знаков`;
}

/**
 * Начало текста для колонки списка (S-AI-VIS-2).
 *
 * Рез по границе слова, а не по счётчику символов: обрубок «…договорились о поста»
 * читается как опечатка, а не как обрыв. Перевод строки в превью схлопывается в
 * пробел — расшифровка размечена репликами, и в одну строку таблицы они не влезут.
 *
 * Текст короче лимита не трогаем вовсе: многоточие после короткой реплики врало бы
 * о том, что там есть продолжение.
 */
export function textPreview(text: string | null | undefined, limit = 120): string {
  if (typeof text !== 'string') return '';
  const flat = text.replace(/\s+/g, ' ').trim();
  if (flat.length <= limit) return flat;
  const cut = flat.slice(0, limit);
  const lastSpace = cut.lastIndexOf(' ');
  // Слово длиннее лимита (ссылка, склейка без пробелов) — режем по символам,
  // иначе `lastSpace === -1` дал бы пустую строку.
  const body = lastSpace > 0 ? cut.slice(0, lastSpace) : cut;
  return `${body.trimEnd()}…`;
}

// ═══════════════════════════════════════════════════════
// S-TR-VTT-1: очистка субтитровой разметки (вкладка «Файл»).
//
// Zoom / Teams / Телемост отдают расшифровку как `.vtt` или `.srt` — форматы для
// ПЛЕЕРА, а не для чтения: каждая реплика обёрнута номером куба и таймкодом. До
// этой функции файл клался в `transcripts.content` как есть, и служебные строки
// (в `.srt` ≈ треть объёма) уезжали в промпт каждого прогона, в поиск по разделу
// и в глаза читателю.
//
// Определяем формат по СОДЕРЖИМОМУ, не по расширению: выгрузка субтитров,
// сохранённая как `.txt`, — обычный случай, а `.vtt` с обычным текстом внутри
// портить нечем (без маркеров функция возвращает вход как есть).
// ═══════════════════════════════════════════════════════

/** Таймкод-строка: `00:00:12.480 --> 00:00:15.120` (+ настройки позиции у WebVTT). */
const CUE_TIMING = /-->/;
/** Порядковый номер куба `.srt` — строка, состоящая только из цифр. */
const CUE_NUMBER = /^\d+$/;
/** Заголовок файла WebVTT (может нести кодировку: `WEBVTT - Kind: captions`). */
const VTT_HEADER = /^WEBVTT(\s|$)/;
/** Блоки метаданных WebVTT, идущие до первой реплики. */
const VTT_BLOCK = /^(NOTE|STYLE|REGION)(\s|$)/;
/** Инлайн-теги WebVTT: `<v Иван>`, `<c.yellow>`, `<00:00:12.480>`. */
const VTT_INLINE_TAG = /<\/?[^>]*>/g;

/**
 * Похоже ли содержимое на субтитры. Два маркера сразу, а не один: одинокая
 * стрелка `-->` встречается в обычном тексте (схемы, стрелки в заметках), а
 * `WEBVTT` без таймкодов — не субтитры, а упоминание формата.
 */
export function looksLikeSubtitles(text: string): boolean {
  if (VTT_HEADER.test(text.trimStart())) return true;
  const lines = text.split(/\r?\n/);
  const timings = lines.filter((l) => CUE_TIMING.test(l)).length;
  // Два таймкода = минимум две реплики. Одна — совпадение, не формат.
  return timings >= 2;
}

/**
 * Снять субтитровую разметку, оставив речь.
 *
 * Не трогает текст, в котором маркеров формата нет: `.txt` с обычной расшифровкой
 * проходит насквозь байт в байт. Это важнее аккуратности разбора — вкладка «Файл»
 * принимает любой текстовый файл, и порча обычного текста была бы хуже, чем
 * недочищенные субтитры.
 *
 * Подряд идущие реплики склеиваются в абзац через пробел: в исходнике перенос
 * строки стоит там, где кончился ТИТР, а не фраза, и построчный вывод читается
 * как столбик обрывков. Абзац рвётся на пустой строке исходника — там смысловая
 * граница есть.
 */
export function stripSubtitleMarkup(text: string): string {
  if (!looksLikeSubtitles(text)) return text;

  const paragraphs: string[] = [];
  let current: string[] = [];
  const flush = () => {
    if (current.length > 0) {
      paragraphs.push(current.join(' '));
      current = [];
    }
  };

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === '') {
      flush();
      continue;
    }
    if (VTT_HEADER.test(line) || VTT_BLOCK.test(line)) continue;
    if (CUE_TIMING.test(line)) continue;
    if (CUE_NUMBER.test(line)) continue;

    const speech = line.replace(VTT_INLINE_TAG, '').trim();
    if (speech !== '') current.push(speech);
  }
  flush();

  return paragraphs.join('\n\n');
}
