/**
 * Русское счётное числительное.
 *
 * Правило, а не `n === 1 ? 'задача' : 'задач'`: тернарник молча врёт на 2–4
 * («2 задач») и на 21 («21 задач» вместо «21 задача»). Вынесено в общий
 * помощник, чтобы правило жило в проекте один раз: до этого его копия была в
 * `domain/month-cells.ts` (`pluralEvents`), и вторая копия рядом с ней
 * разъехалась бы так же, как разъехались правила ОПФ в трёх местах.
 *
 * Возвращает ТОЛЬКО форму слова, без числа: вызывающий сам решает, как
 * склеивать («79 задач», «задач: 79», «выполненных задач — 79»).
 */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  // 11–19 — исключение целиком: последняя цифра тут ни при чём (11, 12, 14 → «задач»).
  if (abs > 10 && abs < 20) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}
