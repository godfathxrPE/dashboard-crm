// ═══════════════════════════════════════════════════════
// S-DEBT-TRUTH-1: батчинг фильтра `.in()` для PostgREST.
//
// ЗАЧЕМ. PostgREST передаёт `.in()` в query string: `?id=in.(uuid,uuid,…)`. Тысяча uuid —
// это ~36 КБ URL, и запрос упирается в лимит длины строки запроса (413/414 в зависимости
// от прокси) ЕЩЁ ДО того, как доедет до Postgres. Проявляется не как «медленно», а как
// упавший запрос — на канале, в котором накопилась переписка.
//
// В проекте уже записана обратная грабля (W3 из 068): ПУСТОЙ `.in()` тоже роняет
// PostgREST. Поэтому обе границы живут здесь, а не расползаются копиями по хукам:
// пустой вход → ноль батчей (запроса просто нет), длинный → нарезка.
//
// ⚠️ Батчинг меняет один запрос на N — порядок строк между батчами НЕ сохраняется.
//    Всё, что зависит от порядка (`.order(...)`), обязано сортировать/группировать
//    результат само, а не полагаться на порядок конкатенации.
// ═══════════════════════════════════════════════════════

/**
 * Сколько id уезжает одним `.in()`.
 *
 * 200 uuid ≈ 7 КБ query string — с запасом и под дефолтный лимит nginx (8 КБ на строку
 * запроса), и под остальные части URL (select, order, эмбеды).
 */
export const IN_BATCH = 200;

/**
 * Нарезать список для `.in()`. Пустой вход → пустой массив батчей: вызывающий получает
 * ноль итераций и ни одного запроса (та же защита, что `enabled: ids.length > 0`).
 */
export function chunkForIn<T>(ids: readonly T[], size: number = IN_BATCH): T[][] {
  if (size < 1) throw new Error('chunkForIn: размер батча должен быть ≥ 1');
  const batches: T[][] = [];
  for (let i = 0; i < ids.length; i += size) batches.push(ids.slice(i, i + size));
  return batches;
}

/**
 * Прогнать `fetchBatch` по батчам и склеить результат.
 *
 * Батчи идут последовательно намеренно: параллельный `Promise.all` по десяти батчам —
 * десять одновременных запросов на открытие канала, а спешить тут некуда. Порядок
 * итогового массива — порядок батчей (см. ⚠️ в шапке файла).
 */
export async function fetchInBatches<Id, Row>(
  ids: readonly Id[],
  fetchBatch: (batch: Id[]) => Promise<Row[]>,
  size: number = IN_BATCH,
): Promise<Row[]> {
  const out: Row[] = [];
  for (const batch of chunkForIn(ids, size)) {
    out.push(...(await fetchBatch(batch)));
  }
  return out;
}
