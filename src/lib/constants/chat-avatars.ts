// ═══════════════════════════════════════════════════════
// S-CHAT-HUB-1e: палитра генерируемых аватаров каналов.
//
// ИСКЛЮЧЕНИЕ из правила «никаких хардкод-цветов». Правило существует ради тем: цвет
// интерфейса обязан меняться вместе с темой. Здесь цвет — не оформление, а ИДЕНТИЧНОСТЬ
// канала: аватар должен опознаваться одинаково в любой из шести тем, как это работает у
// section-цветов навигации (TextNavSidebar держит те же хексы прямо в файле). Поэтому
// пары зафиксированы здесь именованным словарём, а не разведены по CSS-переменным.
//
// Каждая пара — тёмная: белые инициалы поверх. Контраст белого к СВЕТЛОМУ (первому)
// концу градиента посчитан и вынесен в комментарий — это худший случай, тёмный конец
// заведомо лучше. Ниже 3.5:1 в палитру не берём.
// ═══════════════════════════════════════════════════════

export interface ChannelGradient {
  /** Человекочитаемое имя оттенка — чтобы палитру можно было обсуждать словами. */
  name: string;
  /** Светлый конец (135deg, левый верх). */
  from: string;
  /** Тёмный конец (правый низ). */
  to: string;
}

export const CHANNEL_GRADIENTS: readonly ChannelGradient[] = [
  { name: 'teal',    from: '#0F766E', to: '#134E4A' }, // 5.5:1
  { name: 'violet',  from: '#7C3AED', to: '#5B21B6' }, // 5.7:1
  { name: 'orange',  from: '#C2410C', to: '#7C2D12' }, // 4.6:1
  { name: 'emerald', from: '#047857', to: '#064E3B' }, // 5.5:1
  { name: 'cyan',    from: '#0E7490', to: '#164E63' }, // 5.4:1
  { name: 'rose',    from: '#E11D48', to: '#9F1239' }, // 4.6:1
  { name: 'indigo',  from: '#4F46E5', to: '#3730A3' }, // 6.1:1
  { name: 'amber',   from: '#B45309', to: '#78350F' }, // 4.4:1
] as const;

/**
 * djb2 по строке. Math.random ЗАПРЕЩЁН: аватар обязан быть одинаковым между рендерами,
 * вкладками и устройствами — иначе один и тот же канал каждый раз выглядит новым.
 *
 * `| 0` держит число в int32 (переполнение — часть алгоритма), `>>> 0` в конце снимает
 * знак: остаток от деления отрицательного числа в JS отрицательный, и индекс уехал бы
 * за границы массива.
 */
export function djb2(input: string): number {
  let hash = 5381;
  for (let i = 0; i < input.length; i += 1) {
    hash = ((hash << 5) + hash + input.charCodeAt(i)) | 0;
  }
  return hash >>> 0;
}

/** Пара градиента по стабильному ключу (id канала). */
export function gradientFor(key: string): ChannelGradient {
  return CHANNEL_GRADIENTS[djb2(key) % CHANNEL_GRADIENTS.length];
}

/**
 * Инициалы названия: первые буквы двух первых слов («Завод Атлант» → «ЗА»), одно слово —
 * две первые буквы. Кириллица через `toUpperCase()`, без транслита.
 *
 * Ведущая пунктуация с токена снимается, а токен без единой буквы/цифры отбрасывается
 * целиком. Найдено смоуком 1e: «Стратек — внедрение» давало «С—», потому что тире после
 * сплита по пробелам — полноценный токен. Знаки в названиях встречаются постоянно
 * (тире, скобки, «/»), и инициалы из них читаются как поломка вёрстки.
 *
 * Пустая строка на выходе легальна (название из одних знаков или эмодзи) — вызывающий
 * рисует пустой градиент, это лучше вопросительного знака.
 */
export function channelInitials(title: string): string {
  const words = title
    .trim()
    .split(/\s+/)
    .map((w) => w.replace(/^[^\p{L}\p{N}]+/u, ''))
    .filter(Boolean);
  if (words.length === 0) return '';
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}
