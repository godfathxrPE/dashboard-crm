// S-TL-2: курсор ленты — чистые функции, без React Query и без Supabase.
//
// Вынесены из хука ровно ради тестируемости: правило «полная страница → есть ещё,
// неполная → дно» и склейка страниц — это то, что ломается тихо, и юнит-тест на них
// не должен тянуть ни QueryClient, ни браузерный клиент.
// ═══════════════════════════════════════════════════════

import type { TimelineEvent } from '@/types/timeline';

/**
 * Лимит СТРАНИЦЫ, а не источника.
 *
 * До S-TL-2 это был `PER_SOURCE_LIMIT`: каждая из шести веток RPC отдавала до 50
 * строк, и «лента» означала «до 50 от каждого источника». На проде в такой потолок
 * упирались 3 сделки из 19 — у «Стратек — внедрение» 143 задачи против показанных 50,
 * и остальное не показывалось и не запрашивалось.
 */
export const TIMELINE_PAGE_SIZE = 50;

/**
 * Курсор keyset-пагинации: ПАРА, а не один `ts`.
 *
 * События одной секунды реальны (в проде 159 пар в окне ±5 сек), и по одному `ts`
 * страница либо потеряла бы строки, либо повторила их. `id` уникален по построению
 * (`${kind}:${uuid}`) и приходит из того же SQL, что задаёт порядок.
 */
export interface TimelineCursor {
  ts: string;
  id: string;
}

/**
 * Курсор следующей страницы по последней полученной — или `undefined`, если дно.
 *
 * Признак дна — НЕПОЛНАЯ страница, а не пустая: пустая страница означала бы лишний
 * запрос в конце каждой ленты, длина которой кратна `pageSize`. Ровно полная страница
 * на последнем экране стоит одного холостого запроса — это цена того, что «Показать
 * раньше» не врёт.
 */
export function nextTimelineCursor(
  page: readonly TimelineEvent[],
  pageSize: number = TIMELINE_PAGE_SIZE,
): TimelineCursor | undefined {
  if (page.length < pageSize || page.length === 0) return undefined;
  const last = page[page.length - 1];
  return { ts: last.date, id: last.id };
}

/**
 * Склейка загруженных страниц в одну ленту.
 *
 * Плоская конкатенация БЕЗ дедупа — намеренно. Дубль между страницами означает, что
 * серверный keyset разъехался (например, из внутреннего `order by` ветки пропал
 * тай-брейк по `id`), и молча склеить его здесь — значит спрятать дефект, который
 * иначе виден глазами. Порядок страниц = порядок запросов, порядок внутри страницы
 * задан SQL (`ts desc, id desc`) — пересортировывать нечего.
 */
export function flattenTimelinePages(
  pages: readonly (readonly TimelineEvent[])[] | undefined,
): TimelineEvent[] {
  if (!pages) return [];
  return pages.flat() as TimelineEvent[];
}
