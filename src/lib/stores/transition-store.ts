import { create } from 'zustand';
import type { Project } from '@/lib/hooks/use-projects';

/**
 * Единая точка открытия модалки перехода стадии (S-R2-TRANSITION-1b).
 *
 * ЗАЧЕМ СТОР, А НЕ useState В КАЖДОМ ВЫЗЫВАЮЩЕМ. На детальной странице сделки
 * одновременно живут чеврон/полоса стадий и кнопки исхода, на доске — драг и
 * «следующая стадия». С локальным состоянием два таких пути открыли бы ДВЕ модалки
 * поверх друг друга (риск §3.1.9). Здесь состояние одно и модалка смонтирована
 * ровно один раз в `GlobalModals` — два инстанса структурно невозможны.
 *
 * Стор НЕ персистится: незавершённый переход не должен «воскресать» после
 * перезагрузки — данные сделки к тому моменту уже могли измениться.
 */

export interface TransitionRequest {
  project: Project;
  toStageId: string;
  /**
   * «Вернуть в работу»: переход на первую стадию со сбросом исхода. Причина при
   * этом НЕ требуется (стадия не won/lost), а `loss_*`/`won_*` гасятся тем же
   * UPDATE — это часть перехода, а не отдельная правка.
   */
  resetOutcome?: boolean;
  /**
   * Колбэк ПОСЛЕ успешного перехода. Нужен для доводок, которые вызывающий делал
   * сразу после `moveToStageId` до 1b: доска показывает подсказку «запланируй
   * следующий шаг». Дёргать её в момент открытия модалки нельзя — тост
   * (z-50) уехал бы ПОД оверлей модалки (z-999), а его кнопка открыла бы вторую
   * модалку под первой.
   */
  onCommitted?: () => void;
}

interface TransitionStore {
  request: TransitionRequest | null;
  open: (request: TransitionRequest) => void;
  close: () => void;
}

export const useTransitionStore = create<TransitionStore>((set, get) => ({
  request: null,
  open: (request) => {
    // Повторный open поверх открытой модалки игнорируем: иначе клик по соседней
    // стадии из-под оверлея подменил бы цель уже заполняемой формы.
    if (get().request) return;
    set({ request });
  },
  close: () => set({ request: null }),
}));
