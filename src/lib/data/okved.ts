/**
 * Код ОКВЭД («10.13.2», «64.19», «62») → человеческая отрасль, либо null.
 *
 * Разбираем ТОЛЬКО класс (первые две цифры): подкласс/группа/подгруппа дробят
 * справочник до сотен строк, а в поле «Отрасль» нужна крупная категория, по которой
 * менеджер фильтрует список компаний глазами.
 *
 * Мусор на входе (пустая строка, буквы, «ИНН») — null, а не исключение: реестр иногда
 * отдаёт неожиданное, а UI не должен падать из-за поля-подсказки. По той же причине
 * не бросаем и на однозначном коде: «1» → класс 1 → «Сельское и лесное хозяйство».
 */
export function okvedToIndustry(code: string | null | undefined): string | null {
  if (typeof code !== 'string') return null;

  const m = code.trim().match(/^(\d{1,2})/);
  if (!m) return null;

  const cls = Number(m[1]);
  // Ключ переопределений — всегда двузначный («01», «10»): в ОКВЭД класс пишется с
  // ведущим нулём, и `'1'` из `.match` без padStart не нашёл бы «01».
  const key = String(cls).padStart(2, '0');

  const override = CLASS_OVERRIDES[key];
  if (override) return override;

  const section = SECTIONS.find((s) => cls >= s.from && cls <= s.to);
  return section ? section.industry : null;
}
