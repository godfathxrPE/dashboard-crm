// Классификация сбоя LLM. Отдельный файл БЕЗ обращений к Deno — так его импортирует
// и проверяет vitest (`tests/unit/llm-error-kind.test.ts`): классы ошибок решают,
// показывать ли пользователю кнопку «Повторить», и проверять их зеркалом по тексту
// файла было бы слабее, чем прогнать саму функцию.

/**
 * Класс сбоя — то, что вызывающий может ПОКАЗАТЬ и на что может опереться UI.
 *
 * S-LLM-SEARCH-1. Появился из боевого случая: три нажатия «Повторить» подряд на
 * `credit balance is too low`. Повтор там не помогал и помочь не мог, но интерфейс
 * не отличал «нет доступа к провайдеру» от «модель не справилась» и предлагал
 * одно и то же действие. Класс — не украшение: по нему решается, показывать ли
 * кнопку повтора вообще.
 */
export type LlmErrorKind = 'access' | 'upstream' | 'shape' | 'network';

/**
 * HTTP-код → класс. Разложение по смыслу «поможет ли повтор»:
 *   access   — не поможет никогда: ключ, права, деньги (401/402/403 и 400 про баланс);
 *   upstream — поможет позже: лимит или сбой апстрима (429, 5xx);
 *   shape    — поможет: модель не вернула структуру (422 адаптера);
 *   network  — поможет: сеть или таймаут (status 0).
 *
 * ⚠️ Исчерпание кредитов приходит РАЗНЫМИ кодами: у OpenRouter это 402, у Anthropic —
 * 400 `invalid_request_error` с текстом про credit balance. Поэтому одного кода мало,
 * и `classifyLlmError` дополнительно смотрит на тело ответа — но только чтобы
 * КЛАССИФИЦИРОВАТЬ; наружу тело по-прежнему не отдаётся (там детали ключа и тарифа).
 *
 * Остальные коды → `upstream`: он показывает кнопку повтора, то есть ошибается в
 * сторону «дать попробовать», а не в сторону тупика без выхода.
 */
export function classifyLlmError(status: number, upstreamBody = ''): LlmErrorKind {
  if (status === 0) return 'network';
  if (status === 422) return 'shape';
  if (status === 401 || status === 402 || status === 403) return 'access';
  if (status === 400 && /credit balance|insufficient|billing|quota/i.test(upstreamBody)) {
    return 'access';
  }
  return 'upstream';
}
