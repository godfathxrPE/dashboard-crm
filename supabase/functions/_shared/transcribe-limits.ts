/**
 * Потолок одного аудиофрагмента для `transcribe`.
 *
 * Groq принимает до 25 МБ; 20 — наш запас на служебные поля multipart и на то, что
 * платформенные лимиты тела запроса ниже провайдерских. Зеркало `MAX_CHUNK_BYTES` в
 * `src/lib/transcribe/audio.ts` (клиентская нарезка целится в тот же размер).
 */
export const MAX_AUDIO_BYTES = 20_000_000;

/**
 * Потолок длительности голосового из Telegram, секунды.
 *
 * ⚠️ ГРАНИЦА СМЫСЛОВАЯ, А НЕ ТЕХНИЧЕСКАЯ. Три минуты Whisper переварит и в одном
 *    куске; дело в другом — быстрый ввод длиннее трёх минут это уже не быстрый ввод,
 *    а расшифровка встречи, для которой в CRM есть свой путь (AI Hub с нарезкой,
 *    вычиткой и привязкой к сущности). Пропустив её сюда, мы получили бы «задачу» из
 *    часового разговора.
 */
export const MAX_VOICE_SECONDS = 180;
