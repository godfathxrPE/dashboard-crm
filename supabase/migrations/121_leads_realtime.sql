-- ЧТО БЫЛО. Лид — единственная сущность ядра без живого обновления: канбан и
-- очередь дня у двух менеджеров расходятся до минуты (`staleTime` 60 с плюс
-- инвалидации только своих мутаций). Лид — ОБЩИЙ ПУЛ, его разбирают несколько
-- человек, и «я уже звонил» приходит позже, чем второй звонок тому же клиенту;
-- у приватных задач та же задержка стоит дешевле.
--
-- ⚠️ Realtime уважает RLS: подписчик получает событие только по строке, которую
-- ему отдаёт `leads_select` (org-wide, 117). Второго контура доступа не появляется.
--
-- REPLICA IDENTITY НЕ меняем: default (PK) достаточно для INSERT/UPDATE, а на
-- DELETE клиенту довольно факта удаления — old-строка в payload ему не нужна
-- (клиентский `useRealtimeSync` всё равно инвалидирует ключ целиком, а не патчит).
--
-- Таблиц, колонок, функций и политик миграция не трогает ⇒ реген типов не нужен.
-- ═══════════════════════════════════════════════════════════════════════════

alter publication supabase_realtime add table public.leads;

