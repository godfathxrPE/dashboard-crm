-- 132 — quotes: «отклонено» без причины больше невозможно
-- (S-DEAL-ORG-2, задача 1). СТАТУС: НАПИСАНА, НЕ ПРИМЕНЕНА — применяет гейт Cowork
-- через MCP apply_migration.
--
-- 131 завела `quotes.rejection_reason`, `ActiveQuoteCard` пишет её кнопкой
-- «Отклонено». Но статус можно было поставить и руками — селектом в `QuoteModal`,
-- минуя поток с причиной, и в базе не было ничего, что бы это остановило. Отказ без
-- причины не отличается от отказа, причину которого забыли: среза «почему проигрываем»
-- из такой таблицы не собрать никогда.
--
-- Инвариант: `rejected` ⇒ причина непустая. Пробелы не проходят (`btrim`) — «   »
-- заполненностью не является, а форма их пропустила бы.
--
-- ⚠️ `NOT VALID` НЕ СТАВИТСЯ намеренно. Строк-нарушителей на проде НОЛЬ (проверено
-- гейтом 08.09: `quotes` — 3 строки, `rejected` ни одной), бэкфилл не нужен, и
-- отложенная валидация в этой ситуации ничего не спасает, зато прячет будущие
-- нарушения: NOT VALID проверяет только новые строки, но и старые тогда остаются
-- вне гарантии, а `validate constraint` никто уже не позовёт.
--
-- ⚠️ ПОРЯДОК ВЫКАТКИ. Клиент едет ПЕРВЫМ (`rejected` убран из селекта `QuoteModal`,
-- выход из `rejected` чистит причину — тот же коммит), CHECK — вторым. Наоборот
-- модалка начнёт ловить 23514 прямо в форме, где показать его негде: ровно этим
-- закончился `leads_decision_role_check` (#70).
--
-- RLS/индексы/гранты НЕ трогаются: ограничение табличное, политики 053 табличные же.
-- ═══════════════════════════════════════════════════════

alter table public.quotes
  add constraint quotes_rejected_needs_reason
  check (
    status <> 'rejected'
    or (rejection_reason is not null and btrim(rejection_reason) <> '')
  );

comment on constraint quotes_rejected_needs_reason on public.quotes is
  'S-DEAL-ORG-2: отклонённое КП обязано нести причину (непустую после btrim). Ставится потоком «Отклонено» в ActiveQuoteCard; статус rejected убран из селекта QuoteModal, чтобы форма не ловила 23514.';
