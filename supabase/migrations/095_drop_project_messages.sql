-- Guard: голый `drop table` из публикации падает, если таблицы в ней нет
-- (повторный apply / ручное вмешательство). Симметрично add-guard'ам 068/092/094.
do $$
begin
  if exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'project_messages'
  ) then
    alter publication supabase_realtime drop table public.project_messages;
  end if;
end $$;

drop table if exists public.project_messages;
