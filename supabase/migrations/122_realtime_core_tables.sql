-- ⚠️ ЭФФЕКТ ШИРЕ ТРЁХ ХУКОВ. `activity_log` — источник ленты сущности, org-ленты
-- дашборда и правого дровера. После включения они станут живыми у всех, кто держит
-- страницу открытой. Это и есть цель, но `activity_log` пишут ещё и триггеры
