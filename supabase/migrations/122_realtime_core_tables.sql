-- лечится сужением `queryKey` инвалидации в `use-activity-log`, а не откатом
-- миграции: сначала факт, потом правка.
--
-- ⚠️ Realtime уважает RLS: подписчик получает событие только по строке, которую
-- ему отдаёт SELECT-политика соответствующей таблицы. Второго контура доступа
-- не появляется — ровно тот же аргумент, что в 121.
--
-- REPLICA IDENTITY НЕ меняем: default (PK) достаточно для INSERT/UPDATE, а на
-- DELETE клиенту довольно факта удаления — клиентский `useRealtimeSync`
-- инвалидирует ключ целиком, а не патчит строку, и old-строка ему не нужна.
--
-- Кода миграция не требует вовсе: подписки уже написаны и корректны — починка
-- живёт целиком в БД. Таблиц, колонок, функций и политик не трогает
-- ⇒ реген типов не нужен, advisors не меняются (публикация не объект RLS).
-- ═══════════════════════════════════════════════════════════════════════════

alter publication supabase_realtime add table public.contacts;
alter publication supabase_realtime add table public.companies;
alter publication supabase_realtime add table public.activity_log;

