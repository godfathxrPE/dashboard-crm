-- 082 — S-SEC-GRANTS-ROOT: сузить default privileges в корне + снять `MAINTAIN`.
--
-- Третий и последний спринт по грантам. 080 и 081 убирали ПОСЛЕДСТВИЯ — снимали широкие
-- привилегии с уже существующих таблиц. Здесь снимается ПРИЧИНА, из-за которой они там
-- оказались и появились бы снова на следующей же новой таблице.
--
-- Что раздаётся каждой новой таблице в `public` (снято с прода `pg_default_acl` 2026-07-27,
-- Postgres 17.6):
--   grantor `postgres`       → postgres, authenticated, service_role = `arwdDxtm`
--   grantor `supabase_admin` → postgres, anon, authenticated, service_role = `arwdDxtm`
-- То есть `grant select, insert …` в шапке миграции не сужает ничего (урок 075), а revoke
-- в 080/081 вычистил только уже созданные таблицы — дефолты остались широкими, и таблица
-- №45 пришла бы такой же. Именно так и было: `segments` (077) и `stage_transitions` (078)
-- сужались руками в своих же миграциях.
--
-- Плюс невычищенный остаток: **`MAINTAIN`** (`m`, новинка PG 17) держится у `authenticated`
-- на **всех 44 таблицах** — ни 075, ни 080, ни 081 её не снимали, потому что искали по трём
-- именам. MAINTAIN даёт VACUUM / ANALYZE / REINDEX / CLUSTER / REFRESH MATERIALIZED VIEW.
--
-- Почему это гигиена, а не заделка дыры: **PostgREST не исполняет utility-команды вообще** —
-- только DML и вызовы функций, поэтому ни `VACUUM`, ни `ANALYZE`, ни `REINDEX` через REST не
-- отправить. (Аргумент «их нельзя выполнить внутри транзакции» верен лишь для VACUUM и
-- REINDEX CONCURRENTLY: ANALYZE и обычный REINDEX транзакционны — на него опираться нельзя.)
-- Риск от MAINTAIN — не эксплуатация, а привилегия вне модели RLS, которая всплывёт
-- в следующем аудите.
--
-- Поведение не меняется. Откат — обратный `grant` / `alter default privileges … grant`.
--
-- Применяет гейт Cowork через apply_migration (под ролью `postgres` — это существенно, см. 3).

------------------------------------------------------------------------
-- 1. КОРЕНЬ: дефолты роли `postgres` на таблицы в `public`.
--
--    После этого новая таблица, созданная миграцией, приходит с `arwd` у `authenticated` —
--    DML под RLS и ничего сверх. Шапка миграции с `grant select …` наконец начинает
--    означать то, что написано.
--
--    `service_role` не трогаем — он ходит в обход RLS по назначению.
--    `anon` в дефолтах `postgres` и не было (он есть только в дефолтах `supabase_admin`,
--    см. 3).
------------------------------------------------------------------------
alter default privileges for role postgres in schema public
  revoke truncate, references, trigger, maintain on tables from authenticated;

------------------------------------------------------------------------
-- 2. ПОСЛЕДСТВИЕ: снять `MAINTAIN` с уже существующих таблиц.
--
--    Одной строкой по всей схеме, а не точечно: иначе метрика «широких привилегий 0»
--    перестанет сходиться на половине таблиц. `ALL TABLES IN SCHEMA` разворачивается
--    в момент исполнения — новые таблицы под него не попадают, их закрывает шаг 1.
------------------------------------------------------------------------
revoke maintain on all tables in schema public from authenticated;

------------------------------------------------------------------------
-- 3. Ограничение, которое НЕЛЬЗЯ починить миграцией — и потому становится конвенцией.
--
--    Дефолты `supabase_admin` (та строка, что раздаёт полный набор **включая `anon`**)
--    правке недоступны: `postgres` не член `supabase_admin`
--    (`pg_has_role('postgres','supabase_admin','MEMBER')` = false на 2026-07-27), а
--    `ALTER DEFAULT PRIVILEGES FOR ROLE` требует членства.
--
--    ⇒ **Таблицы в `public` создаются только миграциями.** Миграция применяется под
--      `postgres` и подчиняется его дефолтам, которые сужены шагом 1. Таблица, созданная
--      через UI дашборда Supabase, идёт под `supabase_admin` и придёт с полным набором
--      привилегий — **у `anon` тоже**, то есть в обход всей работы 056/075/080/081/082.
--      Таблиц с грантами `anon` сейчас 0 — конвенция де-факто соблюдалась; зафиксирована
--      в `docs/schema.md`, чтобы соблюдалась и дальше.
--
--    Дефолты на ФУНКЦИИ (`f` = `X` у `authenticated`) осознанно НЕ трогаем: большинство
--    функций проекта — RPC, которые клиент обязан вызывать, и сужение дефолта потребовало
--    бы явного `grant execute` у каждой. Это смена конвенции на весь проект, отдельное
--    решение. Цена известна и принята: хвост 056b (`stamp_task_completed_at`,
--    `sync_project_stage`) придётся вычищать вручную и впредь.
--
--    Дефолты на SEQUENCES не трогаем: в схеме 0 sequences (все ключи `uuid`), правки
--    требует не дефолт, а факт появления первой последовательности.

------------------------------------------------------------------------
-- 4. ⚠️ Метрика: `information_schema.role_table_grants` **НЕ показывает `MAINTAIN`**.
--
--    Проверено на проде 2026-07-27: у `projects` в `relacl` стоит `authenticated=arwdm`,
--    а `information_schema` отдаёт по ней ровно `DELETE,INSERT,SELECT,UPDATE`, и
--    `privilege_type = 'MAINTAIN'` не находится нигде (0 строк по всей схеме). Это вью
--    стандарта SQL, нестандартной привилегии в нём нет.
--
--    ⇒ Проверять MAINTAIN **только по каталогу**, иначе запрос «MAINTAIN не осталось»
--      вернёт 0 и будет выглядеть зелёным независимо от реального состояния:
--
--      select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace
--      where n.nspname = 'public' and c.relkind = 'r'
--        and array_to_string(c.relacl, ',') like '%authenticated=%m%';   -- ожидание: 0
--
--    Для TRUNCATE / REFERENCES / TRIGGER `information_schema` пригодна (они стандартные),
--    но каталожный вариант надёжнее и покрывает все четыре разом.
