-- 131 — quotes.rejection_reason: ПРИЧИНА ОТКЛОНЕНИЯ КП
-- (S-DEAL-ORG-1, виджет W4 спеки deal-v2 — организационный блок).
--
-- Спека W4 требует кнопку «Отклонено» с причиной. Колонки под причину в `quotes`
-- нет, и соблазн положить её в `notes` надо снять явно: `notes` — это ТЕКСТ САМОГО
-- ПРЕДЛОЖЕНИЯ (его правят в QuoteModal и показывают в строке списка), а не журнал
-- решений. Приписка «отклонили из-за цены» через месяц неотличима от условий КП, и
-- среза «все КП, отклонённые из-за цены» из такого поля не собрать никогда.
--
-- Аддитивно: NULL у всех существующих строк — легальное состояние («причина не
-- записана»), бэкфилла нет и быть не может (решения приняты до появления поля).
--
-- RLS НЕ ТРОГАЕТСЯ намеренно: политики 053 табличные, не колоночные —
-- `quotes_update` уже пускает owner/admin/manager и ровно им же UI показывает
-- кнопку «Отклонено» (`canEditQuotes`). Отдельной политики на колонку не нужно.
--
-- Индекса нет: поле читается вместе со строкой КП, самостоятельных выборок по нему
-- сегодня нет. Появится срез «причины отказов» — индекс заведёт та миграция.
-- ═══════════════════════════════════════════════════════

alter table public.quotes add column if not exists rejection_reason text;

comment on column public.quotes.rejection_reason is
  'S-DEAL-ORG-1 (W4): причина отклонения КП. Заполняется кнопкой «Отклонено»; к notes отношения не имеет — notes это текст предложения.';
