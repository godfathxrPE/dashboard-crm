-- 116 — S-FIX-BATCH-1: чистка задач, осевших от неудавшихся прогонов миграции
--
-- ⚠️ НЕ ПРИМЕНЯТЬ БЕЗ ЯВНОГО ПОДТВЕРЖДЕНИЯ ВЛАДЕЛЬЦА. Миграция удаляет 398 строк
--    ФИЗИЧЕСКИ: колонки `deleted_at` в проекте нет ни у одной таблицы (hard delete
--    — правило проекта), поэтому «пометить удалёнными» здесь технически нечем.
--    Отката нет. Сначала прогнать SELECT из блока «Что именно удаляется» ниже.
--
-- ── Что случилось ──────────────────────────────────────────────────────────
-- `MigrationTool` (/settings/migration) импортирует JSON-экспорт старого дашборда.
-- Шаг «projects» падал КАЖДЫЙ прогон: он писал в `projects.stage`, а этой колонки
-- нет с переезда на воронки (pipeline_id/stage_id). Шаги были независимы, поэтому
-- шаг «tasks» проходил — и наливал весь план личными задачами без `project_id`.
--
-- Пять прогонов (11.07, 13.07, 14.07, 23.07, 01.08) → 398 строк в «Личном».
-- Каждая строка плана лежит там ровно в 3 копиях: владелец видел на экране дубли
-- «Складской учет», «Закупки», «Продажи, Ценообразование, Скидки».
--
-- Причина устранена в коде тем же PR: шаг проектов идёт первым и переносит
-- старый id → новый, задачи привязываются по этой карте, а при упавшем шаге
-- проектов импорт задач не выполняется вовсе.
--
-- ── Что НЕ трогаем ─────────────────────────────────────────────────────────
-- Остальные 39 задач без проекта — настоящая личная работа (март–апрель, звонки,
-- «Уточнить у Рената Кусаметова» от 07.08, смоук-строки от 08.08). Они вне набора:
-- отбор ограничен пятью датами прогонов.
--
-- ── Чем рискуем ────────────────────────────────────────────────────────────
-- Набор не полностью инертен, владелец должен знать до подтверждения:
--   • 32 строки проведены в «Выполнено» (батчи 11.07/13.07/14.07) — по ним есть
--     история работы, хотя сами строки дублируют план проекта;
--   • 2 строки с исполнителем, 2 с дедлайном, 1 с тайм-блоком;
--   • 89 строк несут company_id/contact_id.
-- Внешних ссылок нет: task_dependencies / baseline_tasks / automation_runs по
-- этому набору пусты, дочерних задач (parent_task_id) нет — CASCADE ничего не
-- утянет за собой.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Что именно удаляется (прогнать ПЕРЕД apply, глазами сверить выборку) ────
-- select id, text, lane, company_id, contact_id, assigned_to, deadline, created_at
-- from public.tasks
-- where project_id is null
--   and wbs_code is null
--   and created_at::date in
--       (date '2026-07-11', date '2026-07-13', date '2026-07-14',
--        date '2026-07-23', date '2026-08-01')
-- order by created_at, id;

do $$
declare
  v_count int;
begin
  select count(*) into v_count
  from public.tasks
  where project_id is null
    and wbs_code is null
    and created_at::date in
        (date '2026-07-11', date '2026-07-13', date '2026-07-14',
         date '2026-07-23', date '2026-08-01');

  -- Гвард, а не формальность: набор описан по разведке от 09.08.2026. Если данные
  -- с тех пор разошлись — в эти же дни что-то дописали, часть строк уже убрали
  -- руками — миграция обязана упасть, а не удалить «примерно то же самое».
  if v_count <> 398 then
    raise exception
      'S-FIX-BATCH-1: ожидалось 398 строк к удалению, найдено %. Данные разошлись с разведкой — пересобрать выборку, не применять вслепую.',
      v_count;
  end if;

  delete from public.tasks
  where project_id is null
    and wbs_code is null
    and created_at::date in
        (date '2026-07-11', date '2026-07-13', date '2026-07-14',
         date '2026-07-23', date '2026-08-01');

  raise notice 'S-FIX-BATCH-1: удалено % задач-сирот от прогонов MigrationTool', v_count;
end $$;
