-- 103 — S-OKVED-1: основной код ОКВЭД компании из ЕГРЮЛ.
--
-- ЗАЧЕМ. DaData в ответе `findById/party` уже отдаёт `data.okved` — основной код
-- ОКВЭД-2, — а нормализатор S-INN-1 его выбрасывал. Из этого кода детерминированно
-- (локальным справочником разделов, `src/lib/data/okved.ts`) выводится отрасль:
-- на живой БД 245 компаний из 261 без `industry`, и 209 из них — с ИНН, то есть
-- отрасль им можно проставить тем же кликом «Заполнить по ИНН», без нового провайдера
-- и без платы за вызов. Сам код тоже нужен хранить: по нему сверяют вид деятельности
-- перед договором, и он — единственный способ переразобрать отрасль, если справочник
-- уточнят.
--
-- ЧТО ЗДЕСЬ. Одна колонка `companies.okved`.
--
-- ⚠️ `okved` И `industry` — РАЗНЫЕ ВЕЩИ, И ЭТО ИНВАРИАНТ СПРИНТА.
--    `okved` — факт реестра (код «10.13.2»), пишется только lookup-ом. `industry` —
--    рабочая классификация для человека («Производство пищевых продуктов»), её видит
--    менеджер в таблице компаний, в CommandPalette и в CSV-экспорте. Код в поле
--    «Отрасль» не пишется ни при каких условиях: в проде уже лежат 5 записей с голыми
--    кодами (`10.13`, `10.13.2` ×2, `10.13.4`, `10.26.12`) — ровно тот результат,
--    который эта колонка и должна прекратить. Существующие значения НЕ мигрируем:
--    это данные в проде, чистка — решение человека, не миграции.
--
-- ⚠️ НАЗВАНИЕ ОКВЭД В БАЗЕ НЕ ДУБЛИРУЕТСЯ. DaData отдаёт только код; человеческое
--    имя приходит из локального справочника. Положить сюда ещё и текст значило бы
--    завести вторую копию словаря в данных — она разойдётся с кодом справочника при
--    первой же его правке, и после этого непонятно, какая версия истинная.
--
-- Индекса НЕТ намеренно: по ОКВЭД сейчас не фильтруют и не группируют, а B-tree на
-- 261 строке — мёртвый вес. Заведём, когда появится аналитика по отраслям.
--
-- RLS не трогаем: колонка в уже защищённой таблице, новых политик не нужно.
-- Гранты не трогаем: `authenticated` уже имеет arwd на `companies`, привилегии в
-- Postgres выдаются на таблицу, а не на колонку.
--
-- Применяет гейт (apply → gen-types → advisors → ролевые смоки).
--
-- Откат:
--   alter table public.companies drop column if exists okved;
-- ═══════════════════════════════════════════════════════

alter table public.companies
  add column if not exists okved text;

comment on column public.companies.okved is
  'S-OKVED-1 (103): основной код ОКВЭД-2 из ЕГРЮЛ (data.okved DaData). Факт реестра: заполняется только lookup-ом, руками не редактируется и в форме не показывается. Человеческая отрасль выводится из кода справочником src/lib/data/okved.ts и живёт в companies.industry.';
