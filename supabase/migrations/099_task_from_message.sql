-- 099 — CHAT-HUB волна 2, фаза 2.1 слой 1: задача из сообщения.
--
-- ЗАЧЕМ. В чате постоянно звучит «надо позвонить», «нужно выставить счёт» — и умирает
-- в ленте. Из сообщения должна рождаться задача: выделил смысл → карточка подтверждения
-- → задача в борде. Здесь — единственное, что для этого нужно от схемы: обратная ссылка
-- задачи на сообщение-источник.
--
-- ЧТО ЗДЕСЬ. Одна колонка `tasks.source_message_id` и два индекса на неё.
--
-- ⚠️ КОЛОНКА ЗАПОЛНЯЕТСЯ ТОЛЬКО ОДНИМ ПУТЁМ — карточкой подтверждения в чате
--    (`TaskFromMessageCard` → `useCreateTask`). Ни один триггер, ни одна RPC её не
--    трогают: это ссылка «откуда пришла задача», а не поле бизнес-логики. Обычная
--    задача из TaskModal приходит с NULL и такой остаётся.
--
-- ⚠️ `ON DELETE SET NULL`, А НЕ CASCADE — ГЛАВНОЕ РЕШЕНИЕ МИГРАЦИИ.
--    Сообщение удаляют (опечатка, передумал) — задача обязана пережить это: она уже
--    живёт своей жизнью, у неё есть исполнитель и срок. Каскад означал бы, что удаление
--    реплики в чате молча сносит работу из борда. Теряется только ссылка на источник —
--    ровно та конвенция FK-связей, что зафиксирована 040.
--
-- ⚠️ PARTIAL UNIQUE — КЛЮЧ ИДЕМПОТЕНТНОСТИ, А НЕ УКРАШЕНИЕ.
--    Одно сообщение → максимум одна задача. Без него двойной клик по «в задачу» (или
--    двое участников канала одновременно) дают две одинаковые задачи, и человек узнаёт
--    об этом только в борде. `WHERE source_message_id IS NOT NULL` обязателен: без
--    предиката вторая же задача из TaskModal (NULL) упала бы на конфликт.
--    NB: в Postgres 17 у уникального индекса по умолчанию NULLS DISTINCT, то есть
--    формально предикат тут не единственная защита — но полагаться на дефолт, который
--    у `NULLS NOT DISTINCT` ровно обратный, значит оставить мину (грабля 085).
--
-- ⚠️ ВТОРОЙ, НЕ-УНИКАЛЬНЫЙ ИНДЕКС — ЯВНО ИЗБЫТОЧЕН, И ЭТО СОЗНАТЕЛЬНО.
--    Чтение ленты (`where source_message_id in (…id сообщений…)`, хук
--    `useTasksBySourceMessages` на каждое открытие канала) полностью обслуживает
--    уникальный индекс выше — по тем же колонкам, и предикат `is not null` совпадает с
--    условием запроса. Отдельный индекс нужен ровно для одного: сценарий «разрешить
--    несколько задач на одно сообщение» обсуждаем, и снятие ограничения не должно
--    молча уводить чтение ленты в seq scan. Цена — вторая запись в индекс на каждый
--    INSERT/UPDATE `tasks`. Если сценарий закроют как ненужный, этот индекс надо снять.
--
-- RLS не трогаем: колонка живёт в уже защищённой таблице, новых политик не нужно.
-- Гранты не трогаем: `authenticated` уже имеет arwd на `tasks`, привилегии в Postgres
-- выдаются на таблицу, а не на колонку.
--
-- ⚠️ НЕ применена — применяет гейт (apply → gen-types → advisors → ролевые смоки).
--
-- Откат:
--   drop index if exists public.idx_tasks_source_message;
--   drop index if exists public.uq_tasks_source_message;
--   alter table public.tasks drop column if exists source_message_id;
-- ═══════════════════════════════════════════════════════

alter table public.tasks
  add column if not exists source_message_id uuid
  references public.messages(id) on delete set null;

comment on column public.tasks.source_message_id is
  'S-CHAT-TASK-1 (099): сообщение чата, из которого создана задача. Заполняется только карточкой подтверждения в чате; ON DELETE SET NULL — удаление сообщения не трогает задачу. Partial unique uq_tasks_source_message: одно сообщение → одна задача.';

-- Идемпотентность «одно сообщение → одна задача» (решение 5 спринта).
create unique index if not exists uq_tasks_source_message
  on public.tasks (source_message_id)
  where source_message_id is not null;

