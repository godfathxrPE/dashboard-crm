// S-OKVED-1: справочник «код ОКВЭД-2 → отрасль».
//
// Модуль чистый и без импортов — тестируется напрямую, без моков и без сети.

import { describe, it, expect } from 'vitest';
import { okvedToIndustry } from '@/lib/data/okved';

describe('okvedToIndustry', () => {
  it('класс переопределяет раздел там, где это важно для профиля клиентов', () => {
    // 10 попадает и в раздел «Обрабатывающие производства» (10–33), и в override.
    // Побеждать обязан override: «Обрабатывающие производства» на мясокомбинате —
    // этикетка, которая не помогает ни фильтру, ни разговору.
    expect(okvedToIndustry('10.13.2')).toBe('Производство пищевых продуктов');
    expect(okvedToIndustry('62.01')).toBe('ИТ и разработка ПО');
    expect(okvedToIndustry('46.90')).toBe('Оптовая торговля');
  });

  it('класс без override отдаёт отрасль раздела', () => {
    expect(okvedToIndustry('64.19')).toBe('Финансы и страхование');
    expect(okvedToIndustry('25.11')).toBe('Обрабатывающие производства');
    expect(okvedToIndustry('43.21')).toBe('Строительство');
    expect(okvedToIndustry('86.10')).toBe('Здравоохранение и соцуслуги');
  });

  it('ведущий ноль не теряется', () => {
    // '01' → класс 1: без padStart ключ '1' не нашёлся бы ни в одном словаре,
    // а сельское хозяйство — не редкий случай в клиентской базе.
    expect(okvedToIndustry('01')).toBe('Сельское и лесное хозяйство');
    expect(okvedToIndustry('01.11')).toBe('Сельское и лесное хозяйство');
    expect(okvedToIndustry('09.10')).toBe('Добыча полезных ископаемых');
  });

  it('код без точки и код класса целиком разбираются так же', () => {
    expect(okvedToIndustry('62')).toBe('ИТ и разработка ПО');
    expect(okvedToIndustry('35')).toBe('Энергетика');
  });

  it('несуществующие классы ОКВЭД-2 дают null — это корректно, а не баг', () => {
    // 34 и 40 — пропуски в нумерации ОК 029-2014, оставленные под будущие виды
    // деятельности. Отрасли у них нет и быть не может.
    expect(okvedToIndustry('34')).toBeNull();
    expect(okvedToIndustry('40.10')).toBeNull();
  });

  it('мусор на входе — null, а не исключение', () => {
    // Поле-подсказка не имеет права ронять форму, что бы ни отдал реестр.
    for (const junk of ['', '   ', 'ИНН', 'ELEC206', null, undefined, '.13']) {
      expect(okvedToIndustry(junk)).toBeNull();
    }
  });

  it('пробелы вокруг кода не мешают', () => {
    expect(okvedToIndustry('  47.11  ')).toBe('Розничная торговля');
  });

  it('никогда не возвращает сам код', () => {
    // Инвариант спринта: в `industry` уходит текст для человека. В проде уже лежат
    // 5 записей с голыми кодами — этого не должно повториться ни через одну ветку.
    for (const code of ['10.13', '10.13.2', '10.13.4', '10.26.12', '99.00']) {
      const industry = okvedToIndustry(code);
      expect(industry).not.toBeNull();
      expect(industry).not.toMatch(/\d/);
    }
  });
});
