import { describe, it, expect } from 'vitest';
import { escapeIlike } from '@/lib/hooks/use-entity-search';

// ═══════════════════════════════════════════════════════
// FIX S-CHAT-TASK-1-BIND: `%` и `_` в пользовательском вводе — маска LIKE, а не
// символы. Без экранирования «100%» ищет «всё, что начинается на 100».
// ═══════════════════════════════════════════════════════

describe('escapeIlike', () => {
  it('процент экранируется — «100%» ищется буквально', () => {
    expect(escapeIlike('100%')).toBe('100\\%');
  });

  it('подчёркивание экранируется — иначе «Ор_ент» матчит «Орнент»', () => {
    expect(escapeIlike('Ор_ент')).toBe('Ор\\_ент');
  });

  it('обратный слэш экранирует сам себя', () => {
    expect(escapeIlike('a\\b')).toBe('a\\\\b');
  });

  it('один проход: уже вставленные слэши повторно не экранируются', () => {
    // Наивная последовательность replace('\\')→replace('%') дала бы 'a\\\\%'.
    expect(escapeIlike('a\\%')).toBe('a\\\\\\%');
  });

  it('обычный ввод не трогается', () => {
    expect(escapeIlike('Ориент Продактс')).toBe('Ориент Продактс');
    expect(escapeIlike('')).toBe('');
  });
});
