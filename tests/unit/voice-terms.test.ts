import { describe, expect, it } from 'vitest';
import { buildVoiceTerms } from '../../supabase/functions/_shared/voice-terms';
import { TERMS_CHAR_BUDGET } from '@/lib/transcribe/glossary';

// ═══════════════════════════════════════════════════════
// S-TG-VOICE-TERMS — имена клиентов и коллег в подсказке Whisper.
//
// ⚠️ ГЛАВНЫЙ ТЕСТ ЗДЕСЬ — РЕГРЕСС НА ИНЦИДЕНТ, а не набор граничных случаев.
//    Боем: «Мукомол» четыре раза подряд распознан как «Мука Мол» / «Мукамол» /
//    дважды латиницей, из-за чего задача осталась без привязки к сделке. Механизм
//    (`terms` → prompt Whisper) существовал и был построен ровно под это — просто
//    бот в него ничего не клал. Значит проверять надо не «функция что-то вернула»,
//    а «на РЕАЛЬНОМ справочнике имя из инцидента попало в подсказку».
//
// ⚠️ ВТОРОЕ ПО ВАЖНОСТИ — ОТСУТСТВИЕ ОБРУБКОВ. `buildPrompt` внутри режет `terms`
//    по живому, и обрезанное имя собственное ХУЖЕ отсутствующего: Whisper подхватит
//    огрызок и выдаст его за слово, то есть подсказка начнёт производить тот самый
//    дефект, который чинит. Отрицательная проверка тут обязана быть структурной
//    («каждый элемент совпадает с одним из входных»), а не списком примеров.
// ═══════════════════════════════════════════════════════

/**
 * Справочник, снятый с боевой БД 2026-08-20 (`projects`, `type='client'`,
 * `updated_at desc`) — вместе с мусором тестовых сделок и хвостовым пробелом
 * в «Ориент Продактс », который в базе действительно есть.
 */
const DEALS = [
  'Фитнес Десерты. WMS',
  'Тест',
  'Перспектива',
  'Чусовская мельница',
  'Ориент Продактс ',
  'Хлебпродукт-2',
  'ЭЙЧ ЭНД ЭН',
  'Мукомол',
  'Продовольственный фонд',
  'Test1',
  'Стратек',
  'Аграрная группа',
  'Хороший вкус',
  'АО "АГРАРНАЯ ГРУППА МП"',
  'ОМК',
  'Завод Атлант',
  'Дмитровские колбасы',
];

/** Пять профилей организации на ту же дату. */
const PEOPLE = ['Daniyar Murzagaliyev', 'Алексей Романченко', 'Иван Петров', 'Иван Тесла', 'Олег'];

const items = (terms: string) => (terms === '' ? [] : terms.split(', '));

describe('боевой справочник укладывается в бюджет подсказки', () => {
  const out = buildVoiceTerms({ deals: DEALS, people: PEOPLE }, TERMS_CHAR_BUDGET);

  // ⛔ РЕГРЕСС НА ИНЦИДЕНТ. Восьмая сделка по свежести — если отбор однажды
  //    начнёт брать «сколько-нибудь первых», этот тест обязан упасть.
  it('«Мукомол» попадает в подсказку — иначе спринт бессмысленен', () => {
    expect(items(out)).toContain('Мукомол');
  });

  it('строка ровно в бюджете, не длиннее', () => {
    expect(out.length).toBeLessThanOrEqual(TERMS_CHAR_BUDGET);
    // Не «≤», а плотно набито: если однажды станет сильно меньше — набор сломался.
    expect(out.length).toBeGreaterThan(TERMS_CHAR_BUDGET - 20);
  });

  it('свежие сделки вытесняют старые, а не наоборот', () => {
    const picked = items(out);
    expect(picked).toContain('Фитнес Десерты. WMS'); // первая по updated_at
    expect(picked).not.toContain('Дмитровские колбасы'); // последняя, не влезла
  });

  it('люди уступают место сделкам: из пяти доезжает только тот, кто влез в остаток', () => {
    const picked = items(out);
    const people = picked.filter((p) => PEOPLE.some((n) => n.trim() === p));
    expect(people).toEqual(['Иван Петров']);
  });
});

describe('обрубков не бывает ни при каком бюджете', () => {
  // ⚠️ ПРОГОН ПО БЮДЖЕТАМ, А НЕ ОДНА ТОЧКА. Ошибка «влезает ровно на границе»
  //    живёт в одном значении из всего диапазона и по одному примеру не ловится.
  it.each([0, 1, 2, 3, 7, 19, 50, 199, 200, 201, 1000, 10_000])(
    'бюджет %i: длина в пределах и каждый элемент — целое имя',
    (budget) => {
      const out = buildVoiceTerms({ deals: DEALS, people: PEOPLE }, budget);
      expect(out.length).toBeLessThanOrEqual(budget);

      // Каждый элемент обязан совпадать с каким-то входным именем целиком —
      // после снятия кавычек/ОПФ и схлопывания пробелов, но БЕЗ обрезки.
      const whole = new Set([
        ...DEALS.map((d) => d.replace(/[«»"'“”]/g, ' ').replace(/\s+/g, ' ').trim().replace(/^(ООО|ОАО|ЗАО|ПАО|НАО|АО|ИП)\s+/i, '')),
        ...PEOPLE.map((p) => p.trim()),
      ]);
      for (const item of items(out)) expect(whole).toContain(item);
    },
  );

  it('бюджет меньше самого короткого имени → пустая строка, а не огрызок', () => {
    expect(buildVoiceTerms({ deals: ['Мукомол'], people: [] }, 2)).toBe('');
  });

  it('длинное имя пропускается, следующее короткое влезает', () => {
    // 'Продовольственный фонд' (22) не влезает в 12, 'Мукомол' (7) — влезает.
    const out = buildVoiceTerms({ deals: ['Продовольственный фонд', 'Мукомол'], people: [] }, 12);
    expect(out).toBe('Мукомол');
  });
});

describe('форма имени: кавычки и ОПФ снимаются, регистр остаётся', () => {
  // ⚠️ РЕГИСТР — НЕ КОСМЕТИКА. Prompt задаёт Whisper стиль вместе со словарём:
  //    список в нижнем регистре тянет расшифровку в нижний регистр, и «мукомол»
  //    в тексте задачи — это другая ошибка вместо исправленной.
  it.each([
    ['АО "АГРАРНАЯ ГРУППА МП"', 'АГРАРНАЯ ГРУППА МП'],
    ['ООО «Ромашка»', 'Ромашка'],
    ['Ориент Продактс ', 'Ориент Продактс'],
    ['  Хороший   вкус ', 'Хороший вкус'],
  ])('«%s» → «%s»', (raw, expected) => {
    expect(buildVoiceTerms({ deals: [raw], people: [] }, 200)).toBe(expected);
  });

  it('имя короче трёх знаков выбрасывается — зацепиться не за что, а место занимает', () => {
    expect(buildVoiceTerms({ deals: ['МП', 'ОМК'], people: [] }, 200)).toBe('ОМК');
  });
});

describe('дедуп', () => {
  it('ОПФ и кавычки не делают из одной сделки две', () => {
    expect(buildVoiceTerms({ deals: ['Мукомол', 'ООО «МУКОМОЛ»'], people: [] }, 200)).toBe('Мукомол');
  });

  it('человек и сделка с одним именем не дублируются', () => {
    expect(buildVoiceTerms({ deals: ['Стратек'], people: ['Стратек'] }, 200)).toBe('Стратек');
  });

  // ⚠️ ГРАНИЦА ДЕДУПА ЗАФИКСИРОВАНА НАМЕРЕННО, И ОНА УЖЕ ОБМАНУЛА ОДИН ПРОМПТ.
  //    «Аграрная группа» и «АО "АГРАРНАЯ ГРУППА МП"» дублями НЕ считаются: после
  //    `normalizeCompanyName` это «аграрная группа» и «аграрная группа мп» —
  //    разные ключи. Это ДВЕ РАЗНЫЕ СДЕЛКИ в CRM, и схлопывать их «по похожести»
  //    значит завести здесь нечёткое сравнение, которое резолвер отказался заводить
  //    осознанно (273 компании, 39 неразличимых имён после снятия ОПФ).
  it('различающиеся хвостом названия остаются двумя записями', () => {
    const out = buildVoiceTerms({ deals: ['Аграрная группа', 'АО "АГРАРНАЯ ГРУППА МП"'], people: [] }, 200);
    expect(items(out)).toEqual(['Аграрная группа', 'АГРАРНАЯ ГРУППА МП']);
  });

  it('дубль остаётся дублем, даже если оригинал не влез в бюджет', () => {
    // 'Продовольственный фонд' (22) мимо бюджета 10; его же ООО-форма не обязана
    // просочиться следом как «другое имя».
    const out = buildVoiceTerms(
      { deals: ['Продовольственный фонд', 'ООО «Продовольственный фонд»', 'ОМК'], people: [] },
      10,
    );
    expect(out).toBe('ОМК');
  });
});

describe('вырожденные входы', () => {
  it('пустой вход → пустая строка (вызывающий тогда terms не шлёт вовсе)', () => {
    expect(buildVoiceTerms({ deals: [], people: [] }, 200)).toBe('');
  });

  it('только пробелы и пустые строки → пустая строка', () => {
    expect(buildVoiceTerms({ deals: ['', '   ', '«»'], people: ['  '] }, 200)).toBe('');
  });

  it('нечисловой бюджет не роняет и не пропускает всё подряд', () => {
    expect(buildVoiceTerms({ deals: ['Мукомол'], people: [] }, Number.NaN)).toBe('');
  });
});
